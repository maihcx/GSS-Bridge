#!/usr/bin/env bash
set -euo pipefail

fail() {
    echo "FAIL: $1" >&2
    exit 1
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
EXT_DIR="$REPO_ROOT/.specify/extensions/gss-bridge/scripts/bash"

TEMP_ROOT="$(mktemp -d 2>/dev/null || mktemp -d -t 'gss-ignore-test')"
cleanup() {
    rm -rf "$TEMP_ROOT"
}
trap cleanup EXIT

cd "$TEMP_ROOT"
git init -q

TARGET_EXT="$TEMP_ROOT/.specify/extensions/gss-bridge/scripts/bash"
mkdir -p "$TARGET_EXT"
cp -rp "$EXT_DIR"/* "$TARGET_EXT/"

UPDATE_SCRIPT="$TARGET_EXT/update-handoff.sh"
IGNORE_PATH="$TEMP_ROOT/.graphifyignore"

if [ -f "$IGNORE_PATH" ]; then
    fail ".graphifyignore should not exist prior to update-handoff run"
fi

# Step 1: Run update-handoff
FEAT_DIR="$TEMP_ROOT/specs/001-test"
mkdir -p "$FEAT_DIR"
echo "# Spec" > "$FEAT_DIR/spec.md"
echo "# Plan" > "$FEAT_DIR/plan.md"
echo "- [x] T001 Task" > "$FEAT_DIR/tasks.md"

bash "$UPDATE_SCRIPT" --status "ready" --feature-directory "specs/001-test" --actor "antigravity" >/dev/null

if [ ! -f "$IGNORE_PATH" ]; then
    fail ".graphifyignore was not generated by update-handoff"
fi

for pat in ".specify/" ".agents/" ".claude/" ".gemini/" ".cursor/" ".windsurf/" "graphify-out/" "raw/" ".graphify*"; do
    if ! grep -qF "$pat" "$IGNORE_PATH"; then
        fail "Required pattern '$pat' missing in generated .graphifyignore"
    fi
done

# Step 2: Create graphify-out and verify .graphify_build.json
OUT_DIR="$TEMP_ROOT/graphify-out"
mkdir -p "$OUT_DIR"
echo '{"nodes":[],"links":[]}' > "$OUT_DIR/graph.json"

bash "$UPDATE_SCRIPT" --status "complete" --feature-directory "specs/001-test" --actor "antigravity" >/dev/null

BUILD_CFG="$OUT_DIR/.graphify_build.json"
if [ ! -f "$BUILD_CFG" ]; then
    fail "graphify-out/.graphify_build.json was not created"
fi

if ! grep -qF ".specify/" "$BUILD_CFG"; then
    fail ".specify/ not found in .graphify_build.json"
fi

# Step 3: Verify preservation of custom user rules
echo "custom_folder/" >> "$IGNORE_PATH"
bash "$UPDATE_SCRIPT" --status "complete" --feature-directory "specs/001-test" --actor "antigravity" >/dev/null

if ! grep -qF "custom_folder/" "$IGNORE_PATH"; then
    fail "Custom rule custom_folder/ was lost"
fi

echo "test-graphify-ignore-ok"
exit 0
