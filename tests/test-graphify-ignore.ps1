# tests/test-graphify-ignore.ps1 — verify automated Graphify ignore & exclusion scaffolding
$ErrorActionPreference = "Stop"

function Fail {
    param([string]$Message)
    Write-Output "FAIL: $Message"
    exit 1
}

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$ExtDir = Join-Path $RepoRoot ".specify\extensions\gss-bridge\scripts\powershell"
$UpdateScript = Join-Path $ExtDir "update-handoff.ps1"

$tempRoot = Join-Path ([System.IO.Path]::GetTempPath()) "gss-ignore-test-$([Guid]::NewGuid().ToString('N').Substring(0,8))"

try {
    New-Item -ItemType Directory -Force -Path $tempRoot | Out-Null
    Push-Location $tempRoot
    git init | Out-Null

    $targetExt = Join-Path $tempRoot ".specify\extensions\gss-bridge\scripts\powershell"
    New-Item -ItemType Directory -Force -Path $targetExt | Out-Null
    Copy-Item -Recurse -Path (Join-Path $ExtDir "*") -Destination $targetExt

    $tUpdate = Join-Path $targetExt "update-handoff.ps1"
    $ignorePath = Join-Path $tempRoot ".graphifyignore"

    if (Test-Path -LiteralPath $ignorePath) {
        Fail ".graphifyignore should not exist prior to update-handoff run"
    }

    # Step 1: Run update-handoff to trigger automatic exclusion setup
    $featDir = Join-Path $tempRoot "specs/001-test"
    New-Item -ItemType Directory -Force -Path $featDir | Out-Null
    Set-Content -LiteralPath (Join-Path $featDir "spec.md") -Value "# Spec" -Encoding UTF8
    Set-Content -LiteralPath (Join-Path $featDir "plan.md") -Value "# Plan" -Encoding UTF8
    Set-Content -LiteralPath (Join-Path $featDir "tasks.md") -Value "- [x] T001 Task" -Encoding UTF8

    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $tUpdate -Status ready -FeatureDirectory "specs/001-test" -Actor antigravity | Out-Null
    if ($LASTEXITCODE -ne 0) { Fail "update-handoff failed" }

    if (-not (Test-Path -LiteralPath $ignorePath)) {
        Fail ".graphifyignore was not generated by update-handoff"
    }

    $ignoreContent = Get-Content -LiteralPath $ignorePath -Raw
    $requiredPatterns = @(
        ".specify/",
        ".agents/",
        ".claude/",
        ".gemini/",
        ".cursor/",
        ".windsurf/",
        "graphify-out/",
        "raw/",
        ".graphify*"
    )
    foreach ($pat in $requiredPatterns) {
        if ($ignoreContent -notmatch [regex]::Escape($pat)) {
            Fail "Required pattern '$pat' missing in generated .graphifyignore"
        }
    }

    # Step 2: Create graphify-out and verify .graphify_build.json is populated
    $outDir = Join-Path $tempRoot "graphify-out"
    New-Item -ItemType Directory -Force -Path $outDir | Out-Null
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText((Join-Path $outDir "graph.json"), '{"nodes":[],"links":[]}', $utf8NoBom)

    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $tUpdate -Status complete -FeatureDirectory "specs/001-test" -Actor antigravity | Out-Null
    if ($LASTEXITCODE -ne 0) { Fail "update-handoff complete failed" }

    $buildCfgPath = Join-Path $outDir ".graphify_build.json"
    if (-not (Test-Path -LiteralPath $buildCfgPath)) {
        Fail "graphify-out/.graphify_build.json was not created"
    }

    $buildCfg = Get-Content -LiteralPath $buildCfgPath -Raw | ConvertFrom-Json
    if (-not $buildCfg.excludes) {
        Fail "excludes missing in .graphify_build.json"
    }
    if ($buildCfg.excludes -notcontains ".specify/") {
        Fail ".specify/ not found in .graphify_build.json excludes"
    }

    # Step 3: Verify preservation of custom user rules
    Add-Content -LiteralPath $ignorePath -Value "`n# Custom User Rule`ncustom_folder/`n" -Encoding UTF8
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $tUpdate -Status complete -FeatureDirectory "specs/001-test" -Actor antigravity | Out-Null
    $reloaded = Get-Content -LiteralPath $ignorePath -Raw
    if ($reloaded -notmatch "custom_folder/") {
        Fail "Custom rule custom_folder/ was wiped out by Ensure-GraphifyExclusions"
    }

    Write-Output "test-graphify-ignore-ok"
} finally {
    Pop-Location
    Remove-Item -Recurse -Force -LiteralPath $tempRoot -ErrorAction SilentlyContinue
}
exit 0
